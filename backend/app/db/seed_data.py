def seed_demo_data(db: Session, force: bool = False) -> dict:
    """
    Populates database with botanical demo records.
    If force=False, seeds only if plants table is empty.
    """
    existing_plants_count = db.query(PlantModel).count()
    if existing_plants_count > 0 and not force:
        return {
            "seeded": False,
            "message": f"Database already contains {existing_plants_count} plants. Seeding skipped.",
            "plants": existing_plants_count,
            "tasks": db.query(CareTaskModel).count(),
            "journal": db.query(JournalEntryModel).count(),
        }

    if force:
        # Clear existing
        db.query(JournalEntryModel).delete()
        db.query(CareTaskModel).delete()
        db.query(PlantModel).delete()
        db.commit()

    # Insert plants
    for p in SEED_PLANTS:
        db.add(PlantModel(**p))
    db.commit()

    # Insert tasks
    for t in SEED_TASKS:
        db.add(CareTaskModel(**t))
    db.commit()

    # Insert journal entries
    for j in SEED_JOURNAL:
        db.add(JournalEntryModel(**j))
    db.commit()

    return {
        "seeded": True,
        "message": "Botanical demonstration data successfully seeded into database.",
        "plants": len(SEED_PLANTS),
        "tasks": len(SEED_TASKS),
        "journal": len(SEED_JOURNAL),
    }
